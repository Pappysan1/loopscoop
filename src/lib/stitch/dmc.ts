function hexToRgb(hex: string) {
  const h = hex.replace('#', '')
  return {
    r: parseInt(h.slice(0, 2), 16),
    g: parseInt(h.slice(2, 4), 16),
    b: parseInt(h.slice(4, 6), 16),
  }
}

export function nearestDmc(hex: string): DmcFloss {
  const rgb = hexToRgb(hex.startsWith('#') ? hex : `#${hex}`)
  let best = DMC[0]
  let bestD = Infinity
  for (const floss of DMC) {
    const c = hexToRgb(floss.hex)
    const d = (c.r - rgb.r) ** 2 + (c.g - rgb.g) ** 2 + (c.b - rgb.b) ** 2
    if (d < bestD) {
      bestD = d
      best = floss
    }
  }
  return best
}
